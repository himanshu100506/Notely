package com.notely.model;

import java.util.Objects;

/**
 * Represents a lightweight label that can be attached to one or more notes.
 *
 * <h3>OOP concepts applied</h3>
 * <ul>
 *   <li><b>Encapsulation</b> — all fields are {@code private};
 *       access is through getters and setters only.</li>
 *   <li><b>Value equality</b> — {@link #equals} and {@link #hashCode}
 *       are overridden so two Tag objects with the same {@code id} are
 *       considered equal.  This is critical because Notes store their
 *       tags in a {@code HashSet<Tag>}: without a correct hashCode the
 *       set cannot detect duplicates.</li>
 * </ul>
 *
 * <h3>Database mapping</h3>
 * Maps to the {@code tags} table (columns: id, name).
 */
public class Tag {

    // ────────────────────────── Fields ──────────────────────────

    /** Database primary key (auto-generated by MySQL). */
    private int id;

    /** Human-readable label, e.g. "java", "urgent", "ideas". */
    private String name;

    // ─────────────────────── Constructors ───────────────────────

    /**
     * No-arg constructor.
     * Required by frameworks and useful when the id is not yet known
     * (e.g. before inserting into the database).
     */
    public Tag() {
    }

    /**
     * Creates a tag with a name only (id assigned later by the database).
     *
     * @param name the tag label
     */
    public Tag(String name) {
        this.name = name;
    }

    /**
     * Full constructor — used when loading from the database.
     *
     * @param id   the database primary key
     * @param name the tag label
     */
    public Tag(int id, String name) {
        this.id = id;
        this.name = name;
    }

    // ──────────────────── Getters and Setters ──────────────────

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    // ──────────────── equals / hashCode / toString ─────────────

    /**
     * Two tags are equal when they share the same database id.
     * This guarantees correct behaviour inside a {@code HashSet<Tag>}.
     */
    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (o == null || getClass() != o.getClass()) return false;
        Tag tag = (Tag) o;
        return id == tag.id;
    }

    /**
     * Consistent with {@link #equals} — based on {@code id} alone.
     */
    @Override
    public int hashCode() {
        return Objects.hash(id);
    }

    /**
     * Returns a concise, human-readable representation.
     * Example: {@code Tag{id=3, name='java'}}
     */
    @Override
    public String toString() {
        return "Tag{id=" + id + ", name='" + name + "'}";
    }
}
